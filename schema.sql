    constraint ck_clients_adult          check (birth_date <= current_date - interval '18 years'),
    constraint ck_clients_email_formato  check (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]{2,}$'),
    constraint ck_clients_phone_formato  check (phone ~ '^\+?[0-9]{7,15}$')
);

